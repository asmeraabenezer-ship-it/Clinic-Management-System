const PrescriptionsPage = {
  currentPage: 1,
  limit: 10,
  filterStatus: '',

  async load() {
    const content = document.getElementById('page-content');
    content.innerHTML = `
      <div class="page-header">
        <div class="page-header-info">
          <h2>Prescriptions</h2>
          <p>E-prescriptions, pharmacy fulfillment, dispensing, and printable Rx slips</p>
        </div>
        <div class="page-header-actions">
          ${Auth.hasRole('doctor', 'admin') ? `
            <button class="btn btn-primary" onclick="PrescriptionsPage.showCreate()">
              <i class="fas fa-prescription"></i> Write Prescription
            </button>
          ` : ''}
        </div>
      </div>

      <div class="search-filter-bar">
        <select class="filter-select" id="rx-filter-status" onchange="PrescriptionsPage.onStatusFilter(this.value)">
          <option value="">All Statuses</option>
          <option value="pending">Pending Dispensing</option>
          <option value="dispensed">Fully Dispensed</option>
          <option value="partially_dispensed">Partially Dispensed</option>
        </select>
        <button class="btn btn-secondary" onclick="PrescriptionsPage.loadList()"><i class="fas fa-sync-alt"></i></button>
      </div>

      <div class="card">
        <div class="card-body" style="padding: 0;" id="rx-table-container">
          <div class="loading-spinner"><i class="fas fa-spinner fa-spin"></i></div>
        </div>
        <div id="rx-pagination"></div>
      </div>
    `;

    await this.loadList();
  },

  onStatusFilter(val) {
    this.filterStatus = val;
    this.currentPage = 1;
    this.loadList();
  },

  async loadList() {
    const container = document.getElementById('rx-table-container');
    if (!container) return;
    container.innerHTML = '<div class="loading-spinner"><i class="fas fa-spinner fa-spin"></i></div>';

    try {
      const res = await API.prescriptions.list({
        page: this.currentPage,
        limit: this.limit,
        status: this.filterStatus
      });

      const prescriptions = res.data || res.prescriptions || [];
      const pagination = res.pagination;

      if (!prescriptions.length) {
        showEmptyState(
          'rx-table-container',
          'fas fa-prescription-bottle',
          'No Prescriptions Found',
          'Prescriptions generated by physicians will appear here.',
          Auth.hasRole('doctor', 'admin') ? `<button class="btn btn-primary" onclick="PrescriptionsPage.showCreate()"><i class="fas fa-prescription"></i> Write Prescription</button>` : ''
        );
        document.getElementById('rx-pagination').innerHTML = '';
        return;
      }

      container.innerHTML = `
        <div class="table-wrapper">
          <table class="table">
            <thead>
              <tr>
                <th>Date</th>
                <th>Patient</th>
                <th>Prescribed By</th>
                <th>Medicines</th>
                <th>Status</th>
                <th style="text-align: right;">Actions</th>
              </tr>
            </thead>
            <tbody>
              ${prescriptions.map(p => {
                const patientName = p.patients ? `${p.patients.first_name} ${p.patients.last_name}` : 'Patient';
                const docName = p.doctors?.profiles ? p.doctors.profiles.full_name : 'Physician';
                const itemsCount = p.prescription_items?.length || 0;

                return `
                  <tr>
                    <td>${formatDate(p.created_at)}</td>
                    <td><strong>${patientName}</strong> <span style="font-size:11px;color:var(--gray-400);">(${p.patients?.patient_number || ''})</span></td>
                    <td>Dr. ${docName}</td>
                    <td><span class="badge-scheduled" style="padding: 2px 8px; border-radius: var(--radius-sm); font-size: 12px; font-weight: 600;">${itemsCount} Medication${itemsCount !== 1 ? 's' : ''}</span></td>
                    <td>${getStatusBadge(p.status)}</td>
                    <td style="text-align: right;">
                      <div style="display: inline-flex; gap: 4px;">
                        <button class="btn btn-sm btn-secondary" title="View Rx" onclick="PrescriptionsPage.viewDetails('${p.id}')">
                          <i class="fas fa-eye"></i>
                        </button>
                        <button class="btn btn-sm btn-outline" title="Print Rx" onclick="PrescriptionsPage.printRx('${p.id}')">
                          <i class="fas fa-print"></i>
                        </button>
                        ${Auth.hasRole('pharmacist', 'admin') && p.status !== 'dispensed' ? `
                          <button class="btn btn-sm btn-success" title="Dispense" onclick="PrescriptionsPage.showDispenseModal('${p.id}')">
                            <i class="fas fa-pills"></i> Dispense
                          </button>
                        ` : ''}
                      </div>
                    </td>
                  </tr>
                `;
              }).join('')}
            </tbody>
          </table>
        </div>
      `;

      renderPagination('rx-pagination', pagination, 'PrescriptionsPage.goToPage');
    } catch (err) {
      container.innerHTML = `<div class="p-4 text-center text-danger">${err.message}</div>`;
    }
  },

  goToPage(p) {
    this.currentPage = p;
    this.loadList();
  },

  async showCreate(preselectedPatientId = null, preselectedDoctorId = null, preselectedAppointmentId = null) {
    try {
      const [patientsRes, doctorsRes, medicinesRes] = await Promise.all([
        API.patients.list({ limit: 100 }),
        API.doctors.list({ limit: 100 }),
        API.medicines.list({ limit: 200 })
      ]);

      const patients = patientsRes.data || patientsRes.patients || [];
      const doctors = doctorsRes.data || doctorsRes.doctors || [];
      const medicines = medicinesRes.data || medicinesRes.medicines || [];

      window._availableMedicines = medicines;

      openModal('Write Medical Prescription (Rx)', `
        <form id="create-rx-form">
          <div class="form-row">
            <div class="form-group">
              <label class="form-label">Patient <span class="required">*</span></label>
              <select id="crx-patient" class="form-control" required>
                <option value="">Select patient...</option>
                ${patients.map(p => `<option value="${p.id}" ${preselectedPatientId === p.id ? 'selected' : ''}>${p.first_name} ${p.last_name} (${p.patient_number || p.phone})</option>`).join('')}
              </select>
            </div>
            <div class="form-group">
              <label class="form-label">Doctor <span class="required">*</span></label>
              <select id="crx-doctor" class="form-control" required>
                <option value="">Select doctor...</option>
                ${doctors.map(d => `<option value="${d.id}" ${preselectedDoctorId === d.id ? 'selected' : ''}>Dr. ${d.profiles?.full_name || d.full_name} (${d.specialization})</option>`).join('')}
              </select>
            </div>
          </div>

          <!-- Medications List -->
          <div style="margin-bottom: 20px;">
            <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 12px;">
              <h4 style="font-size: 14px; font-weight: 700; margin: 0; color: var(--gray-800);">Prescribed Medications</h4>
              <button type="button" class="btn btn-sm btn-outline" onclick="PrescriptionsPage.addMedicineRow()">
                <i class="fas fa-plus"></i> Add Medication
              </button>
            </div>
            <div id="rx-items-container" style="display: flex; flex-direction: column; gap: 10px;">
              <!-- Dynamic rows added here -->
            </div>
          </div>

          <div class="form-group">
            <label class="form-label">General Advice / Special Patient Instructions</label>
            <textarea id="crx-instructions" class="form-control" rows="2" placeholder="e.g. Drink plenty of water, complete the full antibiotic course, avoid dairy with medication..."></textarea>
          </div>

          <div class="card-footer" style="padding: 12px 0 0; background: transparent;">
            <button type="button" class="btn btn-secondary" onclick="closeModal()">Cancel</button>
            <button type="submit" class="btn btn-primary" id="btn-save-rx">Issue Prescription</button>
          </div>
        </form>
      `, 'modal-xl');

      // Add first row
      this.addMedicineRow();

      document.getElementById('create-rx-form').addEventListener('submit', async (e) => {
        e.preventDefault();
        setLoading('#btn-save-rx', true);

        const rows = document.querySelectorAll('.rx-med-row');
        const items = [];

        rows.forEach(r => {
          const medId = r.querySelector('.rx-med-id').value;
          const dosage = r.querySelector('.rx-med-dosage').value.trim();
          const frequency = r.querySelector('.rx-med-freq').value.trim();
          const duration = r.querySelector('.rx-med-dur').value.trim();
          const qty = parseInt(r.querySelector('.rx-med-qty').value) || 1;
          const instr = r.querySelector('.rx-med-inst').value.trim();

          if (medId) {
            items.push({
              medicine_id: medId,
              dosage,
              frequency,
              duration,
              quantity: qty,
              instructions: instr || null
            });
          }
        });

        if (!items.length) {
          showToast('error', 'Validation', 'Please add at least one medication to the prescription.');
          setLoading('#btn-save-rx', false);
          return;
        }

        const payload = {
          patient_id: document.getElementById('crx-patient').value,
          doctor_id: document.getElementById('crx-doctor').value,
          appointment_id: preselectedAppointmentId || null,
          general_instructions: document.getElementById('crx-instructions').value.trim() || null,
          items
        };

        try {
          await API.prescriptions.create(payload);
          showToast('success', 'Prescription Issued', 'Medications added to pharmacy queue.');
          closeModal();
          PrescriptionsPage.loadList();
        } catch (err) {
          showToast('error', 'Error', err.message);
        } finally {
          setLoading('#btn-save-rx', false);
        }
      });
    } catch (err) {
      showToast('error', 'Error', err.message);
    }
  },

  addMedicineRow() {
    const container = document.getElementById('rx-items-container');
    if (!container) return;
    const rowId = `rx-row-${Date.now()}-${Math.random().toString(36).substr(2, 4)}`;

    const medOptions = (window._availableMedicines || []).map(m => {
      return `<option value="${m.id}" data-unit="${m.unit || ''}">${m.name} (${m.strength || ''}) - Stock: ${m.stock_quantity}</option>`;
    }).join('');

    const div = document.createElement('div');
    div.className = 'rx-med-row card';
    div.id = rowId;
    div.style.cssText = 'border: 1px solid var(--gray-200); padding: 12px; background: var(--gray-50);';
    div.innerHTML = `
      <div style="display: grid; grid-template-columns: 2fr 1fr 1fr 1fr 1fr 2fr auto; gap: 8px; align-items: flex-end;">
        <div>
          <label style="font-size: 11px; font-weight: 600; color: var(--gray-500); display: block; margin-bottom: 4px;">Medication</label>
          <select class="form-control rx-med-id" required>
            <option value="">Select drug...</option>
            ${medOptions}
          </select>
        </div>
        <div>
          <label style="font-size: 11px; font-weight: 600; color: var(--gray-500); display: block; margin-bottom: 4px;">Dosage</label>
          <input type="text" class="form-control rx-med-dosage" placeholder="e.g. 500mg" required>
        </div>
        <div>
          <label style="font-size: 11px; font-weight: 600; color: var(--gray-500); display: block; margin-bottom: 4px;">Frequency</label>
          <select class="form-control rx-med-freq">
            <option value="Once daily">Once daily</option>
            <option value="Twice daily">Twice daily</option>
            <option value="Three times daily">Three times daily</option>
            <option value="Four times daily">Four times daily</option>
            <option value="Every 8 hours">Every 8 hours</option>
            <option value="As needed (PRN)">As needed (PRN)</option>
          </select>
        </div>
        <div>
          <label style="font-size: 11px; font-weight: 600; color: var(--gray-500); display: block; margin-bottom: 4px;">Duration</label>
          <input type="text" class="form-control rx-med-dur" placeholder="e.g. 7 days" required>
        </div>
        <div>
          <label style="font-size: 11px; font-weight: 600; color: var(--gray-500); display: block; margin-bottom: 4px;">Quantity</label>
          <input type="number" class="form-control rx-med-qty" value="1" min="1" required>
        </div>
        <div>
          <label style="font-size: 11px; font-weight: 600; color: var(--gray-500); display: block; margin-bottom: 4px;">Instructions</label>
          <input type="text" class="form-control rx-med-inst" placeholder="e.g. Take after food">
        </div>
        <div>
          <button type="button" class="btn btn-sm btn-danger" onclick="document.getElementById('${rowId}').remove()" title="Remove">
            <i class="fas fa-trash"></i>
          </button>
        </div>
      </div>
    `;

    container.appendChild(div);
  },

  async viewDetails(id) {
    try {
      const p = await API.prescriptions.get(id);
      const patientName = p.patients ? `${p.patients.first_name} ${p.patients.last_name}` : 'Unknown';
      const docName = p.doctors?.profiles ? p.doctors.profiles.full_name : 'Physician';

      openModal(`Prescription Details`, `
        <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 16px;">
          <div>
            <div style="font-size: 12px; color: var(--gray-400); text-transform: uppercase; font-weight: 700;">Prescription Date</div>
            <div style="font-size: 16px; font-weight: 800; color: var(--gray-800);">${formatDate(p.created_at)}</div>
          </div>
          <div>${getStatusBadge(p.status)}</div>
        </div>

        <div class="detail-grid" style="margin-bottom: 20px;">
          <div class="detail-item"><label>Patient</label><p><strong>${patientName}</strong> (${p.patients?.patient_number || '-'})</p></div>
          <div class="detail-item"><label>Doctor</label><p>Dr. <strong>${docName}</strong> (${p.doctors?.specialization || 'General'})</p></div>
        </div>

        <div class="table-wrapper" style="margin-bottom: 16px;">
          <table class="table">
            <thead>
              <tr>
                <th>Medicine</th>
                <th>Dosage</th>
                <th>Frequency</th>
                <th>Duration</th>
                <th>Qty</th>
                <th>Instructions</th>
                <th>Status</th>
              </tr>
            </thead>
            <tbody>
              ${(p.prescription_items || []).map(i => `
                <tr>
                  <td><strong>${i.medicines?.name || 'Medicine'}</strong></td>
                  <td>${i.dosage}</td>
                  <td>${i.frequency}</td>
                  <td>${i.duration}</td>
                  <td>${i.quantity}</td>
                  <td>${i.instructions || '-'}</td>
                  <td>
                    <span class="status-badge ${i.is_dispensed ? 'badge-completed' : 'badge-pending'}">
                      ${i.is_dispensed ? 'Dispensed' : 'Pending'}
                    </span>
                  </td>
                </tr>
              `).join('')}
            </tbody>
          </table>
        </div>

        ${p.general_instructions ? `
          <div class="alert alert-info" style="margin-bottom: 16px;">
            <i class="fas fa-info-circle"></i>
            <div><strong>Instructions:</strong> ${p.general_instructions}</div>
          </div>
        ` : ''}

        <div class="card-footer" style="padding: 12px 0 0; background: transparent; display: flex; justify-content: space-between;">
          <button class="btn btn-secondary" onclick="closeModal()">Close</button>
          <div style="display: flex; gap: 8px;">
            <button class="btn btn-outline" onclick="PrescriptionsPage.printRx('${p.id}')">
              <i class="fas fa-print"></i> Print Rx
            </button>
            ${Auth.hasRole('pharmacist', 'admin') && p.status !== 'dispensed' ? `
              <button class="btn btn-success" onclick="closeModal(); PrescriptionsPage.showDispenseModal('${p.id}')">
                <i class="fas fa-pills"></i> Dispense Medications
              </button>
            ` : ''}
          </div>
        </div>
      `, 'modal-lg');
    } catch (err) {
      showToast('error', 'Error', err.message);
    }
  },

  async showDispenseModal(id) {
    try {
      const p = await API.prescriptions.get(id);
      openModal('Dispense Prescription Medications', `
        <form id="dispense-form">
          <div class="alert alert-warning" style="margin-bottom: 16px;">
            <i class="fas fa-exclamation-triangle"></i>
            <div>Check items to fulfill. Dispensing will automatically deduct stock from medicine inventory.</div>
          </div>

          <div class="table-wrapper" style="margin-bottom: 16px;">
            <table class="table">
              <thead>
                <tr>
                  <th style="width: 40px;">Fulfill</th>
                  <th>Medication</th>
                  <th>Required Qty</th>
                  <th>In Stock</th>
                </tr>
              </thead>
              <tbody>
                ${(p.prescription_items || []).map(i => {
                  const stock = i.medicines?.stock_quantity ?? 0;
                  const canFulfill = stock >= i.quantity;
                  return `
                    <tr>
                      <td>
                        <input type="checkbox" class="dispense-check" value="${i.id}" ${i.is_dispensed ? 'disabled' : (canFulfill ? 'checked' : 'disabled')} style="width:18px;height:18px;">
                      </td>
                      <td>
                        <strong>${i.medicines?.name}</strong> (${i.dosage})
                        ${!canFulfill && !i.is_dispensed ? `<div style="font-size:11px;color:var(--danger);font-weight:600;"><i class="fas fa-times-circle"></i> Insufficient stock</div>` : ''}
                      </td>
                      <td>${i.quantity}</td>
                      <td>
                        <span class="${stock < i.quantity ? 'text-danger font-bold' : ''}">${stock} units</span>
                      </td>
                    </tr>
                  `;
                }).join('')}
              </tbody>
            </table>
          </div>

          <div class="card-footer" style="padding: 12px 0 0; background: transparent;">
            <button type="button" class="btn btn-secondary" onclick="closeModal()">Cancel</button>
            <button type="submit" class="btn btn-success" id="btn-confirm-dispense">Confirm & Deduct Stock</button>
          </div>
        </form>
      `);

      document.getElementById('dispense-form').addEventListener('submit', async (e) => {
        e.preventDefault();
        setLoading('#btn-confirm-dispense', true);

        const checked = Array.from(document.querySelectorAll('.dispense-check:checked')).map(c => c.value);
        if (!checked.length) {
          showToast('error', 'Error', 'No items selected for dispensing.');
          setLoading('#btn-confirm-dispense', false);
          return;
        }

        try {
          await API.prescriptions.dispense(id, checked);
          showToast('success', 'Dispensed', 'Prescription filled and inventory deducted.');
          closeModal();
          PrescriptionsPage.loadList();
        } catch (err) {
          showToast('error', 'Error', err.message);
        } finally {
          setLoading('#btn-confirm-dispense', false);
        }
      });
    } catch (err) {
      showToast('error', 'Error', err.message);
    }
  },

  async printRx(id) {
    try {
      const p = await API.prescriptions.get(id);
      const patientName = p.patients ? `${p.patients.first_name} ${p.patients.last_name}` : 'Patient';
      const docName = p.doctors?.profiles ? p.doctors.profiles.full_name : 'Physician';

      const html = `
        <div class="rx-print">
          <div class="rx-header">
            <div class="rx-clinic-name">CLINICCARE MEDICAL CENTER</div>
            <div style="font-size: 13px; color: #555;">123 Healthcare Blvd, Medical District &bull; Tel: (555) 019-2834</div>
            <div style="font-size: 12px; color: #777;">License # CLN-884920 &bull; info@cliniccare.pro</div>
          </div>

          <div class="rx-info">
            <div>
              <p><strong>Patient:</strong> ${patientName}</p>
              <p><strong>Patient #:</strong> ${p.patients?.patient_number || '-'}</p>
              <p><strong>Age / Gender:</strong> ${formatAge(p.patients?.date_of_birth)} / ${p.patients?.gender || '-'}</p>
            </div>
            <div>
              <p><strong>Doctor:</strong> Dr. ${docName}</p>
              <p><strong>Specialization:</strong> ${p.doctors?.specialization || 'General Practitioner'}</p>
              <p><strong>Date:</strong> ${formatDate(p.created_at)}</p>
            </div>
          </div>

          <div class="rx-symbol">&#8478;</div>

          <div class="rx-medicines">
            ${(p.prescription_items || []).map((i, idx) => `
              <div class="rx-medicine-item">
                <div style="display: flex; justify-content: space-between; font-weight: bold; font-size: 15px;">
                  <span>${idx + 1}. ${i.medicines?.name || 'Medicine'} (${i.dosage})</span>
                  <span>Qty: ${i.quantity}</span>
                </div>
                <div style="font-size: 13px; margin-top: 4px; color: #333;">
                  <strong>Sig:</strong> Take ${i.frequency} for ${i.duration}. ${i.instructions ? `(${i.instructions})` : ''}
                </div>
              </div>
            `).join('')}
          </div>

          ${p.general_instructions ? `
            <div style="margin-top: 20px; font-size: 13px; border-left: 2px solid #555; padding-left: 10px;">
              <strong>Doctor's Advice:</strong> ${p.general_instructions}
            </div>
          ` : ''}

          <div class="rx-signature">
            <p>____________________________________</p>
            <p><strong>Dr. ${docName}</strong></p>
            <p style="font-size: 12px; color: #777;">Attending Physician Signature & Stamp</p>
          </div>
        </div>
      `;

      printContent(html);
    } catch (err) {
      showToast('error', 'Print Error', err.message);
    }
  }
};

window.PrescriptionsPage = PrescriptionsPage;
